CREATE DATABASE IF NOT EXISTS lawyersforum CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE lawyersforum;

CREATE TABLE IF NOT EXISTS lawyers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  title VARCHAR(150) NOT NULL DEFAULT '',
  practice_area VARCHAR(150) NOT NULL DEFAULT '',
  bio TEXT,
  email VARCHAR(190) NOT NULL DEFAULT '',
  photo_url VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS articles (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  summary VARCHAR(500) NOT NULL DEFAULT '',
  content MEDIUMTEXT NOT NULL,
  author_id INT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_articles_author FOREIGN KEY (author_id) REFERENCES lawyers(id) ON DELETE SET NULL
) ENGINE=InnoDB;
